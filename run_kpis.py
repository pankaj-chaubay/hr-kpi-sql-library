"""
Runs the HR KPI SQL library on DuckDB and writes each result to ./output.

Data: Human Resources Data Set by Dr. Rich Huebner (fictional, 311 employees).
The SQL is plain ANSI-style SQL with a few DuckDB functions (strptime, last_day,
date_diff, QUALIFY). The same queries run on Snowflake with small changes.

The script also checks two numbers against the Power BI dashboard project
(headcount 207 and 13 leavers in the 12 months to Dec 2018), so both tools
are proven to use the same definitions.

Run:  python run_kpis.py
"""
from pathlib import Path

import duckdb
import pandas as pd

SOURCE = "https://raw.githubusercontent.com/bisquittz/Human-Resources-Dataset-Analysis/main/HRDataset_v14.csv"
HERE = Path(__file__).parent
OUT = HERE / "output"
OUT.mkdir(exist_ok=True)

con = duckdb.connect()
con.register("raw_hr", pd.read_csv(SOURCE, encoding="utf-8-sig"))
con.execute((HERE / "sql" / "00_staging.sql").read_text())

results = {}
for f in sorted((HERE / "sql").glob("0[1-9]_*.sql")):
    df = con.execute(f.read_text()).df()
    if "month_end" in df:
        df["month_end"] = pd.to_datetime(df["month_end"]).dt.date
    df.to_csv(OUT / f"{f.stem}.csv", index=False)
    results[f.stem] = df

att = results["02_attrition_rolling_12m"].set_index("month_end")
dec = att.loc[pd.Timestamp("2018-12-31").date()]
checks = {
    "Headcount Dec 2018 = 207": int(dec["headcount"]) == 207,
    "Leavers 12M to Dec 2018 = 13": int(dec["leavers_12m"]) == 13,
}

with open(HERE / "results.md", "w") as fh:
    fh.write("# Results (generated by run_kpis.py)\n\n")
    for k, v in checks.items():
        fh.write(f"- Check {k}: {'PASS' if v else 'FAIL'}\n")
    fh.write("\n## Attrition, last 4 quarters\n\n")
    q = att[[d.month in (3, 6, 9, 12) for d in att.index]].tail(4).reset_index()
    fh.write(q.to_markdown(index=False) + "\n\n")
    for name in ["03_department_snapshot", "04_leavers_by_reason", "05_source_quality"]:
        fh.write(f"## {name}\n\n" + results[name].to_markdown(index=False) + "\n\n")

print(open(HERE / "results.md").read()[:3000])
assert all(checks.values()), checks
